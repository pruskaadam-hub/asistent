"""Process M.A.R.V.I.N. iCloud calendar requests stored in GitHub.

The private data repository is the durable command queue. The web panel writes
confirmed requests there and this worker executes them through iCloud CalDAV.
The request id is also used as the iCalendar UID, so retrying after a network or
GitHub conflict cannot create a second event.
"""

from __future__ import annotations

import base64
import json
import os
import uuid
from copy import deepcopy
from datetime import date, datetime, time, timedelta, timezone
from urllib.error import HTTPError
from urllib.parse import quote, unquote, urlparse
from urllib.request import Request, urlopen
from zoneinfo import ZoneInfo

# GitHub-hosted runners do not have an OS credential store. Force keyring's
# null backend so icloud-mcp proceeds to the ICLOUD_APP_PASSWORD environment
# fallback instead of raising NoKeyringError before checking it.
os.environ.setdefault("PYTHON_KEYRING_BACKEND", "keyring.backends.null.Keyring")

import icalendar
from icloud_mcp.clients import CalendarClient
from icloud_mcp.config import Settings


VERSION = "2026.10.21-v1"
REPOSITORY = "pruskaadam-hub/asistent-data"
BRANCH = "main"
QUEUE_PATH = "kalendar-pozadavky.json"
SOURCES_PATH = "zdroje.json"
PLAN_PATH = "planovani.json"
GITHUB_API = "https://api.github.com"
LOCAL_TZ = ZoneInfo("Europe/Prague")


def _token() -> str:
    value = os.getenv("MARVIN_GITHUB_TOKEN", "").strip()
    if not value:
        raise RuntimeError("MARVIN_GITHUB_TOKEN is missing.")
    return value


def _github(method: str, path: str, body=None):
    url = f"{GITHUB_API}/repos/{REPOSITORY}/contents/{quote(path)}"
    if method == "GET":
        url += f"?ref={quote(BRANCH)}"
    raw = None if body is None else json.dumps(body).encode()
    request = Request(
        url,
        data=raw,
        method=method,
        headers={
            "Authorization": f"Bearer {_token()}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "Content-Type": "application/json",
            "User-Agent": "marvin-icloud-github-worker",
        },
    )
    with urlopen(request, timeout=45) as response:
        return json.load(response)


def _read_json(path: str) -> tuple[object, str]:
    item = _github("GET", path)
    content = base64.b64decode(item["content"].replace("\n", "")).decode()
    return json.loads(content), item["sha"]


def _write_json(path: str, value: object, sha: str, message: str) -> None:
    content = json.dumps(value, ensure_ascii=False, indent=2) + "\n"
    _github(
        "PUT",
        path,
        {
            "message": message,
            "content": base64.b64encode(content.encode()).decode(),
            "branch": BRANCH,
            "sha": sha,
        },
    )


def _calendar_id(calendar) -> str:
    path = unquote(urlparse(str(getattr(calendar, "url", ""))).path).rstrip("/")
    return path.rsplit("/", 1)[-1] if path else ""


def _source_policy(sources: object) -> tuple[set[str], set[str], dict[str, dict]]:
    if not isinstance(sources, list):
        raise RuntimeError("zdroje.json is not an array.")
    source = next((x for x in sources if x.get("id") == "icloud-cal"), None)
    if not source or source.get("stav") != "Aktivní":
        raise RuntimeError("The icloud-cal source is not Active.")
    readable = set(source.get("calendar_ids", []))
    writable = set(source.get("write_calendar_ids", []))
    metadata = {
        x["calendar_id"]: x
        for x in source.get("kalendare", [])
        if x.get("calendar_id")
    }
    if not writable <= readable:
        raise RuntimeError("Writable iCloud calendars must also be readable.")
    return readable, writable, metadata


def _parse_time(value: str):
    if len(value) == 10:
        return date.fromisoformat(value)
    parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=LOCAL_TZ)


def _target_calendar(client: CalendarClient, calendar_id: str):
    for calendar in client.principal().calendars():
        if _calendar_id(calendar) == calendar_id:
            return calendar
    raise RuntimeError(f"iCloud calendar {calendar_id!r} was not found.")


def _uid_for(request_id: str) -> str:
    # Request ids are generated by the private panel. UUID5 also makes unusual
    # legacy ids safe for an iCalendar UID.
    return f"{uuid.uuid5(uuid.NAMESPACE_URL, 'marvin:' + request_id)}@marvin"


def _find_uid(target, uid: str, start, end) -> bool:
    if isinstance(start, date) and not isinstance(start, datetime):
        start_dt = datetime.combine(start, time.min, LOCAL_TZ)
    else:
        start_dt = start.astimezone(LOCAL_TZ)
    if isinstance(end, date) and not isinstance(end, datetime):
        end_dt = datetime.combine(end, time.min, LOCAL_TZ)
    else:
        end_dt = end.astimezone(LOCAL_TZ)
    for item in target.search(
        start=start_dt - timedelta(days=1),
        end=end_dt + timedelta(days=1),
        event=True,
        expand=True,
    ):
        if str(item.icalendar_component.get("uid", "")) == uid:
            return True
    return False


def _create_event(client: CalendarClient, request: dict) -> tuple[str, str]:
    target = _target_calendar(client, request["calendar_id"])
    start, end = _parse_time(request["start"]), _parse_time(request["end"])
    if end <= start:
        raise RuntimeError("Event end must be after its start.")
    uid = _uid_for(request["id"])
    if _find_uid(target, uid, start, end):
        return uid, "The event already existed; the request was reconciled."
    document = icalendar.Calendar()
    document.add("version", "2.0")
    document.add("prodid", "-//M.A.R.V.I.N.//GitHub iCloud worker//CS")
    event = icalendar.Event()
    event.add("uid", uid)
    event.add("dtstamp", datetime.now(timezone.utc))
    event.add("dtstart", start)
    event.add("dtend", end)
    event.add("summary", str(request["title"]).strip())
    if str(request.get("location", "")).strip():
        event.add("location", str(request["location"]).strip())
    document.add_component(event)
    target.save_event(document.to_ical().decode())
    return uid, f"Created in {target.get_display_name()}."


def _result_patch(request: dict, state: str, summary: str, error: str = "") -> dict:
    now = datetime.now(LOCAL_TZ).isoformat(timespec="seconds")
    return {
        "stav": state,
        "souhrn": summary,
        "chyba": error,
        "zpracovano": now,
        "pokusy": int(request.get("pokusy", 0)) + 1,
        "worker_verze": VERSION,
    }


def _merge_results(results: dict[str, dict]) -> None:
    for attempt in range(3):
        queue, sha = _read_json(QUEUE_PATH)
        if not isinstance(queue, list):
            raise RuntimeError(f"{QUEUE_PATH} is not an array.")
        changed = False
        for request in queue:
            patch = results.get(str(request.get("id", "")))
            if patch:
                request.update(patch)
                changed = True
        if not changed:
            return
        try:
            _write_json(
                QUEUE_PATH,
                queue,
                sha,
                "Asistent: výsledky iCloud kalendářových požadavků",
            )
            return
        except HTTPError as exc:
            if exc.code in (409, 422) and attempt < 2:
                continue
            raise
    raise RuntimeError("Could not merge iCloud request results after conflicts.")


def process_queue() -> tuple[int, int]:
    if os.getenv("ICLOUD_ENABLE_WRITES", "0") != "1":
        raise RuntimeError("ICLOUD_ENABLE_WRITES must equal 1.")
    sources, _ = _read_json(SOURCES_PATH)
    _, writable, _ = _source_policy(sources)
    queue, _ = _read_json(QUEUE_PATH)
    if not isinstance(queue, list):
        raise RuntimeError(f"{QUEUE_PATH} is not an array.")
    pending = [x for x in queue if x.get("stav") == "ceka"]
    if not pending:
        return 0, 0
    results: dict[str, dict] = {}
    ok = 0
    client = CalendarClient(Settings.from_env())
    try:
        for request in pending:
            request_id = str(request.get("id", ""))
            try:
                if not request_id:
                    raise RuntimeError("Request id is missing.")
                if request.get("typ") != "vytvorit-udalost":
                    raise RuntimeError("Only vytvorit-udalost is supported.")
                if request.get("potvrzeno") is not True or request.get("autor") != "Adam":
                    raise RuntimeError("The request lacks Adam's explicit panel confirmation.")
                if request.get("zdroj_zapisu") != "panel":
                    raise RuntimeError("Only requests created by the private panel are accepted.")
                if request.get("calendar_id") not in writable:
                    raise RuntimeError("The target calendar is not writable in zdroje.json.")
                if not str(request.get("title", "")).strip():
                    raise RuntimeError("Event title is empty.")
                uid, summary = _create_event(client, request)
                patch = _result_patch(request, "zpracovano", summary)
                patch["icloud_uid"] = uid
                results[request_id] = patch
                ok += 1
            except Exception as exc:
                results[request_id] = _result_patch(
                    request,
                    "chyba",
                    "The iCloud request failed.",
                    f"{type(exc).__name__}: {exc}",
                )
    finally:
        client.close()
    _merge_results(results)
    return ok, len(pending) - ok


def main() -> None:
    ok, failed = process_queue()
    print(f"iCloud queue complete: {ok} completed, {failed} failed.")


if __name__ == "__main__":
    main()
